"""Browser <-> backend endpoints for a call. The browser never sees the OpenAI key, session id or tools."""
from fastapi import APIRouter, Depends, Header, HTTPException, Request

from ..models.schemas import CallRefIn, CallSessionIn
from ..security import client_ip, order_access_token, require_same_origin
from ..services.live_session import CallError
from .deps import resolve_restaurant

router = APIRouter(prefix="/api/call", dependencies=[Depends(require_same_origin)])


@router.post("/session")
async def create_session(request: Request, body: CallSessionIn):
    app = request.app
    if not app.state.call_limiter.allow(client_ip(request)):
        raise HTTPException(429, "Too many call attempts. Please wait a few minutes.")
    restaurant = resolve_restaurant(request, body.restaurant_id)
    try:
        secret, answer = await app.state.live.create_call(restaurant, body.client_call_id, body.sdp)
    except CallError as exc:
        raise HTTPException(exc.status, exc.message)
    return {"call_secret": secret, "transport": {"type": "webrtc", "sdp": answer}}


def _auth(request: Request, call_id: str, secret: str | None) -> dict:
    if not request.app.state.status_limiter.allow(client_ip(request)):
        raise HTTPException(429, "Slow down")
    doc = request.app.state.live.authenticate(call_id, secret or "")
    if doc is None:
        raise HTTPException(404, "Unknown call")
    return doc


@router.post("/ready")
async def ready(request: Request, body: CallRefIn, x_call_secret: str | None = Header(None)):
    _auth(request, body.client_call_id, x_call_secret)
    await request.app.state.live.mark_ready(body.client_call_id)
    return {"ok": True}


@router.get("/status")
def status(request: Request, client_call_id: str, x_call_secret: str | None = Header(None)):
    doc = _auth(request, client_call_id, x_call_secret)
    app = request.app
    order = app.state.db.orders.find_one({"voice_session_id": doc["_id"], "restaurant_id": doc["restaurant_id"], "status": "confirmed"})
    payload = None
    if order:
        token = order_access_token(app.state.secret, order["_id"])
        payload = {"reference": order["reference"], "url": f"/confirmation/{order['reference']}?t={token}"}
    return {"state": app.state.live.live_status(doc), "order": payload}


@router.post("/end")
async def end(request: Request, body: CallRefIn, x_call_secret: str | None = Header(None)):
    """Ending a call never confirms or discards an order. An unconfirmed order simply expires (24h TTL)."""
    _auth(request, body.client_call_id, x_call_secret)
    request.app.state.live.request_end(body.client_call_id)
    return {"ok": True}


@router.post("/cancel")
async def cancel(request: Request, body: CallRefIn):
    """Cancel while connecting. The 32-hex client_call_id is generated by the browser and acts as the capability.
    Async so the lifecycle change happens on the event loop (never from a worker thread)."""
    if not request.app.state.status_limiter.allow(client_ip(request)):
        raise HTTPException(429, "Slow down")
    known = request.app.state.live.request_cancel(body.client_call_id)
    return {"ok": True, "known": known}
